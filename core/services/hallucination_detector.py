# Known hallucinated method/keyword patterns frequently generated by LLMs
KNOWN_HALLUCINATED_METHODS: dict[str, tuple[str, str]] = {
    "read_file": (
        "Path.read_file() Python pathlib içinde mevcut değildir",
        "Path.read_text() veya Path.read_bytes() kullanın.",
    ),
    "write_file": (
        "Path.write_file() Python pathlib içinde mevcut değildir",
        "Path.write_text() veya Path.write_bytes() kullanın.",
    ),
    "has_key": (
        "dict.has_key() Python 3'te kaldırılmıştır (AI halüsinasyonu)",
        "'key in dict_obj' operatörünü kullanın.",
    ),
}

KNOWN_HALLUCINATED_KWARGS: dict[tuple[str, str], tuple[str, str]] = {
    ("requests", "timeout_ms"): (
        "requests çağrılarında 'timeout_ms' adında bir parametre yoktur",
        "Saniye cinsinden 'timeout=' parametresini kullanın.",
    ),
    ("httpx", "timeout_ms"): (
        "httpx çağrılarında 'timeout_ms' adında bir parametre yoktur",
        "Saniye cinsinden 'timeout=' parametresini kullanın.",
    ),
    ("json.loads", "ignore_errors"): (
        "json.loads() fonksiyonunda 'ignore_errors' parametresi yoktur",
        "try/except json.JSONDecodeError bloğu kullanın.",
    ),
}


@dataclass
class HallucinationFinding:
    """A single detected API or symbol hallucination."""

    file: str
    line: int
    hallucination_type: str  # "MISSING_STDLIB_SYMBOL" | "MISSING_MODULE_ATTR" | "HALLUCINATED_METHOD" | "HALLUCINATED_KWARG"
    symbol: str
    explanation: str
    suggestion: str
    severity: str = "HIGH"

    def to_dict(self) -> dict[str, Any]:
        return {
            "file": self.file,
            "line": self.line,
            "hallucination_type": self.hallucination_type,
            "symbol": self.symbol,
            "explanation": self.explanation,
            "suggestion": self.suggestion,
            "severity": self.severity,
        }


@dataclass
class HallucinationScanResult:
    """Aggregated result of scanning a codebase for AI hallucinations."""

    score: float
    risk_level: str
    files_scanned: int
    findings: list[HallucinationFinding] = field(default_factory=list)

    def to_dict(self) -> dict[str, Any]:
        return {
            "score": round(self.score, 1),
            "risk_level": self.risk_level,
            "files_scanned": self.files_scanned,
            "findings_count": len(self.findings),
            "findings": [f.to_dict() for f in self.findings],
        }


class HallucinatedAPIDetector:
    """Static AST analyzer that verifies imported stdlib symbols and catches hallucinated APIs."""

    @staticmethod
    def _load_safe_module(mod_name: str) -> Any | None:
        """Loads a module only if it is in SAFE_STDLIB_MODULES or already in sys.modules."""
        if mod_name in SAFE_STDLIB_MODULES or mod_name in sys.stdlib_module_names:
            try:
                return importlib.import_module(mod_name)
            except Exception:
                return None
        return None

    def analyze_code(self, content: str, file_label: str = "<snippet>") -> list[HallucinationFinding]:
        """Analyzes Python source code string for hallucinated imports, attributes, and kwargs."""
        findings: list[HallucinationFinding] = []
        try:
            tree = ast.parse(content, filename=file_label)
        except SyntaxError:
            return findings

        # Track alias -> stdlib module name (e.g. `import json as j` -> `j: json`)
        imported_modules: dict[str, str] = {}
        # Track variables initialized from `Path(...)`
        path_vars: set[str] = set()

        for node in ast.walk(tree):
            # 1. `import X`
            if isinstance(node, ast.Import):
                for alias in node.names:
                    bound_name = alias.asname or alias.name.split(".")[0]
                    imported_modules[bound_name] = alias.name

            # 2. `from X import Y`
            elif isinstance(node, ast.ImportFrom):
                mod_name = node.module
                if not mod_name or node.level > 0:
                    continue
                mod_obj = self._load_safe_module(mod_name)
                if mod_obj is not None:
                    for alias in node.names:
                        if alias.name == "*":
                            continue
                        if not hasattr(mod_obj, alias.name):
                            # Check if it's a submodule
                            sub_mod = self._load_safe_module(f"{mod_name}.{alias.name}")
                            if sub_mod is None:
                                findings.append(
                                    HallucinationFinding(
                                        file=file_label,
                                        line=getattr(node, "lineno", 1),
                                        hallucination_type="MISSING_STDLIB_SYMBOL",
                                        symbol=f"{mod_name}.{alias.name}",
                                        explanation=f"'{mod_name}' standart kütüphanesinde '{alias.name}' sembolü bulunmuyor (AI Halüsinasyonu).",
                                        suggestion=f"'{mod_name}' modülünün resmi dokümantasyonundaki geçerli fonksiyon adlarını kontrol edin.",
                                        severity="CRITICAL",
                                    )
                                )

            # 3. Track `p = Path(...)` assignments
            elif isinstance(node, ast.Assign):
                if isinstance(node.value, ast.Call):
                    func = node.value.func
                    func_name = getattr(func, "id", getattr(func, "attr", ""))
                    if func_name == "Path":
                        for target in node.targets:
                            if isinstance(target, ast.Name):
                                path_vars.add(target.id)

        # Second pass: inspect Call nodes for hallucinated attributes & kwargs
        for node in ast.walk(tree):
            if not isinstance(node, ast.Call):
                continue

            lineno = getattr(node, "lineno", 1)
            func = node.func

            # Case A: `mod.attr(...)` on a known stdlib module
            if isinstance(func, ast.Attribute) and isinstance(func.value, ast.Name):
                caller_name = func.value.id
                attr_name = func.attr

                if caller_name in imported_modules:
                    target_mod_name = imported_modules[caller_name]
                    mod_obj = self._load_safe_module(target_mod_name)
                    if mod_obj is not None and not hasattr(mod_obj, attr_name):
                        sub_mod = self._load_safe_module(f"{target_mod_name}.{attr_name}")
                        if sub_mod is None:
                            findings.append(
                                HallucinationFinding(
                                    file=file_label,
                                    line=lineno,
                                    hallucination_type="MISSING_MODULE_ATTR",
                                    symbol=f"{target_mod_name}.{attr_name}",
                                    explanation=f"'{target_mod_name}' modülünde '{attr_name}()' adında bir metod/öznitelik mevcut değil.",
                                    suggestion=f"'{target_mod_name}' üzerindeki geçerli metod isimlerini kullanın.",
                                    severity="CRITICAL",
                                )
                            )

                # Case B: Known hallucinated kwargs (e.g. `requests.get(..., timeout_ms=500)`)
                kw_names = {kw.arg for kw in node.keywords if kw.arg}
                for (pkg_prefix, bad_kw), (reason, fix) in KNOWN_HALLUCINATED_KWARGS.items():
                    full_call = f"{caller_name}.{attr_name}"
                    if (caller_name == pkg_prefix or full_call == pkg_prefix) and bad_kw in kw_names:
                        findings.append(
                            HallucinationFinding(
                                file=file_label,
                                line=lineno,
                                hallucination_type="HALLUCINATED_KWARG",
                                symbol=f"{full_call}({bad_kw}=...)",
                                explanation=reason,
                                suggestion=fix,
                                severity="HIGH",
                            )
                        )

                # Case C: `Path(...).read_file()` or `p.read_file()` or `d.has_key()`
                if attr_name in KNOWN_HALLUCINATED_METHODS:
                    if attr_name in ("read_file", "write_file") and caller_name not in path_vars and caller_name != "Path":
                        continue
                    reason, fix = KNOWN_HALLUCINATED_METHODS[attr_name]
                    findings.append(
                        HallucinationFinding(
                            file=file_label,
                            line=lineno,
                            hallucination_type="HALLUCINATED_METHOD",
                            symbol=f"{caller_name}.{attr_name}()",
                            explanation=reason,
                            suggestion=fix,
                            severity="HIGH",
                        )
                    )

            # Case D: Inline `Path("foo").read_file()`
            elif isinstance(func, ast.Attribute) and isinstance(func.value, ast.Call):
                inner_func = func.value.func
                inner_name = getattr(inner_func, "id", getattr(inner_func, "attr", ""))
                if inner_name == "Path" and func.attr in ("read_file", "write_file"):
                    reason, fix = KNOWN_HALLUCINATED_METHODS[func.attr]
                    findings.append(
                        HallucinationFinding(
                            file=file_label,
                            line=lineno,
                            hallucination_type="HALLUCINATED_METHOD",
                            symbol=f"Path(...).{func.attr}()",
                            explanation=reason,
                            suggestion=fix,
                            severity="HIGH",
                        )
                    )

            # Case E: Hallucinated builtin function calls (e.g. calling something that looks like a builtin)
            elif isinstance(func, ast.Name) and func.id in ("isset", " empty", "strlen"):
                if not hasattr(builtins, func.id):
                    findings.append(
                        HallucinationFinding(
                            file=file_label,
                            line=lineno,
                            hallucination_type="HALLUCINATED_METHOD",
                            symbol=f"{func.id}()",
                            explanation=f"'{func.id}()' Python builtin fonksiyonu değildir (PHP/JS dil karışması halüsinasyonu).",
                            suggestion="Python'da karşılığı olan 'len()' veya 'is not None' ifadelerini kullanın.",
                            severity="HIGH",
                        )
                    )

        return findings

    def scan_repository(
        self, repo_path: Path | str, files: list[Path] | None = None
    ) -> HallucinationScanResult:
        """Scans all Python files in a repository for hallucinated APIs and symbols."""
        root = Path(repo_path).resolve()
        source_files = files if files is not None else discover_source_files(root)
        py_files = [f for f in source_files if f.suffix == ".py"]

        all_findings: list[HallucinationFinding] = []
        for py_file in py_files:
            try:
                rel_path = str(py_file.relative_to(root)).replace("\\", "/")
            except ValueError:
                rel_path = py_file.name

            content = safe_read_file(py_file)
            if not content:
                continue
            all_findings.extend(self.analyze_code(content, file_label=rel_path))

        score = max(0.0, 100.0 - (len(all_findings) * 20.0))
        if len(all_findings) == 0:
            risk_level = "LOW"
        elif len(all_findings) <= 2:
            risk_level = "HIGH"
        else:
            risk_level = "CRITICAL"

        return HallucinationScanResult(
            score=score,
            risk_level=risk_level,
            files_scanned=len(py_files),
            findings=all_findings,
        )
