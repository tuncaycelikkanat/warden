"""AI Hallucinated API, Non-Existent Symbol & Signature Mismatch Detector for WARDEN.

Detects common LLM code-generation hallucinations before runtime:
1. Importing non-existent functions/classes from Python standard library or installed packages
   (e.g. `from json import loads_safe`, `from pathlib import read_file`).
2. Calling non-existent attributes/methods on imported standard library modules
   (e.g. `json.parse(...)`, `os.path.exists_file(...)`).
3. Known LLM Hallucinated API Anti-Patterns:
   - `Path(...).read_file()` / `Path(...).write_file()` (instead of `read_text`/`write_text`)
   - `requests.get(..., timeout_ms=...)` (hallucinated keyword argument)
   - `dict.has_key(...)` (Python 2 remnant hallucinated in Python 3)
   - `asyncio.coroutine` (removed in Python 3.11+)
"""

